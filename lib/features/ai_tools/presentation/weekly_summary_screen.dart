/// A warm, plain-language summary of the mother's own logged data for the past
/// week, generated by the AI strictly from what she recorded.
class WeeklySummaryScreen extends ConsumerStatefulWidget {
  const WeeklySummaryScreen({super.key});

  @override
  ConsumerState<WeeklySummaryScreen> createState() =>
      _WeeklySummaryScreenState();
}

class _WeeklySummaryScreenState extends ConsumerState<WeeklySummaryScreen> {
  bool _busy = false;
  String? _error;
  WeeklySummary? _summary;

  Map<String, dynamic> _buildStats() {
    final since = DateTime.now().subtract(const Duration(days: 7));
    final stats = <String, dynamic>{};

    final bp = (ref.read(bpReadingsProvider).valueOrNull ?? const [])
        .where((r) => r.loggedAt.isAfter(since))
        .toList();
    if (bp.isNotEmpty) {
      final sys = bp.map((e) => e.systolic).reduce((a, b) => a + b) / bp.length;
      final dia = bp.map((e) => e.diastolic).reduce((a, b) => a + b) / bp.length;
      final latest = bp.reduce((a, b) => a.loggedAt.isAfter(b.loggedAt) ? a : b);
      stats['bloodPressure'] = {
        'readings': bp.length,
        'avg': '${sys.round()}/${dia.round()}',
        'latest': '${latest.systolic}/${latest.diastolic}',
      };
    }

    final gl = (ref.read(glucoseReadingsProvider).valueOrNull ?? const [])
        .where((r) => r.loggedAt.isAfter(since))
        .toList();
    if (gl.isNotEmpty) {
      final avg = gl.map((e) => e.mgDl).reduce((a, b) => a + b) / gl.length;
      stats['bloodSugar'] = {
        'readings': gl.length,
        'avgMgDl': avg.round(),
      };
    }

    final wt = (ref.read(weightEntriesProvider).valueOrNull ?? const [])
        .where((r) => r.loggedAt.isAfter(since))
        .toList()
      ..sort((a, b) => a.loggedAt.compareTo(b.loggedAt));
    if (wt.isNotEmpty) {
      stats['weight'] = {
        'latestKg': wt.last.weightKg,
        'changeKg':
            double.parse((wt.last.weightKg - wt.first.weightKg).toStringAsFixed(1)),
      };
    }

    final sl = (ref.read(sleepEntriesProvider).valueOrNull ?? const [])
        .where((r) => r.loggedAt.isAfter(since))
        .toList();
    if (sl.isNotEmpty) {
      final avg = sl.map((e) => e.hours).reduce((a, b) => a + b) / sl.length;
      stats['sleep'] = {
        'nights': sl.length,
        'avgHours': double.parse(avg.toStringAsFixed(1)),
      };
    }
    return stats;
  }

  Future<void> _generate() async {
    final stats = _buildStats();
    if (stats.isEmpty) {
      setState(() => _error =
          'Log some blood pressure, sugar, weight or sleep this week first.');
      return;
    }
    setState(() {
      _busy = true;
      _error = null;
    });
    try {
      final s = await ref.read(documentAiRepositoryProvider).weeklySummary(
            stats: stats,
            context: ref.read(aiContextProvider),
          );
      if (mounted) setState(() => _summary = s);
    } catch (e) {
      if (mounted) {
        setState(() => _error =
            e is StateError ? e.message : 'Could not summarise. Try again.');
      }
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Weekly summary')),
      body: _busy
          ? const LoadingView(message: 'Reviewing your week…')
          : ListView(
              padding: const EdgeInsets.all(AppSpacing.lg),
              children: [
                Text(
                  'A gentle recap of what you logged over the last 7 days.',
                  style: context.textStyles.bodyMedium
                      ?.copyWith(color: context.colors.onSurfaceVariant),
                ),
                const SizedBox(height: AppSpacing.md),
                AppButton(
                  label: _summary == null ? 'Generate summary' : 'Refresh',
                  icon: Icons.auto_awesome,
                  onPressed: _generate,
                ),
                const SizedBox(height: AppSpacing.lg),
                if (_error != null)
                  AppCard(
                    color: context.colors.errorContainer,
                    child: Text(_error!,
                        style: context.textStyles.bodyMedium
                            ?.copyWith(color: context.colors.onErrorContainer)),
                  ),
                if (_summary != null) ..._result(_summary!),
              ],
            ),
    );
  }

  List<Widget> _result(WeeklySummary s) => [
        if (s.summary.isNotEmpty)
          AppCard(child: Text(s.summary, style: context.textStyles.bodyMedium)),
        if (s.highlights.isNotEmpty) ...[
          const SizedBox(height: AppSpacing.md),
          Text('Highlights', style: context.textStyles.titleSmall),
          const SizedBox(height: AppSpacing.xs),
          for (final h in s.highlights)
            Padding(
              padding: const EdgeInsets.symmetric(vertical: 1),
              child: Text('• $h', style: context.textStyles.bodyMedium),
            ),
        ],
        if (s.watchOuts.isNotEmpty) ...[
          const SizedBox(height: AppSpacing.md),
          Text('Worth mentioning to your doctor',
              style: context.textStyles.titleSmall),
          const SizedBox(height: AppSpacing.xs),
          for (final w in s.watchOuts)
            Padding(
              padding: const EdgeInsets.symmetric(vertical: 1),
              child: Text('• $w', style: context.textStyles.bodyMedium),
            ),
        ],
        const SizedBox(height: AppSpacing.md),
        AiDisclaimer(s.disclaimer),
      ];
}
